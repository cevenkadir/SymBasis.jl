#!/usr/bin/env bash
# Orchestrates the full SymBasis vs XDiag.jl vs QuSpin basis-construction benchmark.
#
# Usage:
#   BENCH_SWEEP=quick|large ./run_all.sh
#
# Assumes `python` on PATH is a Python environment with QuSpin installed (locally: activate
# your conda/venv env first, e.g. `conda activate quspin_env`; in CI: `pip install quspin`
# before this script runs -- QuSpin isn't on conda-forge, but ships manylinux wheels on PyPI).
#
# Threads are intentionally left at their defaults (JULIA_NUM_THREADS=auto picks up all local
# cores; OMP_NUM_THREADS is left unset so XDiag's/QuSpin's OpenMP-backed code also uses its own
# default) -- this reports what each library actually does out of the box, rather than an
# artificially single-threaded comparison. Pin JULIA_NUM_THREADS=1/OMP_NUM_THREADS=1 yourself
# beforehand if you want a strictly single-threaded apples-to-apples comparison instead.

set -euo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "$HERE/.." && pwd)"

export JULIA_NUM_THREADS=auto

echo "== BENCH_SWEEP=${BENCH_SWEEP:-quick} =="

echo "-- SymBasis + XDiag.jl (spin) --"
julia --project="$HERE" "$HERE/spin_basis.jl"

echo "-- SymBasis + XDiag.jl (spinless fermion) --"
julia --project="$HERE" "$HERE/fermion_basis.jl"

echo "-- SymBasis + XDiag.jl (spinful fermion) --"
julia --project="$HERE" "$HERE/spinful_fermion_basis.jl"

echo "-- SymBasis + XDiag.jl (boson) --"
julia --project="$HERE" "$HERE/boson_basis.jl"

echo "-- QuSpin (spin, fermion, spinful fermion, boson) --"
if command -v python >/dev/null 2>&1 && python -c "import quspin" >/dev/null 2>&1; then
    python "$HERE/quspin_bench.py"
else
    echo "quspin not importable from the active python -- skipping QuSpin benchmarks" >&2
fi

echo "-- Aggregating results --"
julia --project="$HERE" "$HERE/compare_results.jl"

echo "Done. See $HERE/results/local/benchmarks.md (tables) -- run"
echo "'julia --project=docs docs/make.jl' to render plots from the committed"
echo "$REPO_ROOT/benchmark/results/*.csv (live @example blocks, no image is generated by this"
echo "script). docs/src/benchmarks.md and benchmark/results/*.csv are regenerated by CI on"
echo "every push to main -- this script never touches them locally."
