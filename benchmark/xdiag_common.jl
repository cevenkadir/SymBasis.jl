module XDiagCommon

using XDiag

export build_translation_reflection_group

"""
    build_translation_reflection_group(N::Integer)

Build the dihedral-like `PermutationGroup` generated by a single-site cyclic translation and
a spatial reflection on `N` sites (2N elements total). XDiag has no prebuilt point-group
helper beyond `cyclic_group`/`cyclic_group_irrep` (translation only), so combined
translation+reflection groups must be assembled by hand — mirrors what SymBasis does
internally via `sym(...) ∘ sym(...)`.
"""
function build_translation_reflection_group(N::Integer)
    T = Permutation(collect(circshift(1:N, -1)))
    P = Permutation(collect(reverse(1:N)))
    T_powers = [pow(T, r) for r in 0:(N-1)]
    elems = vcat(T_powers, [P * t for t in T_powers])
    return PermutationGroup(elems)
end

end
